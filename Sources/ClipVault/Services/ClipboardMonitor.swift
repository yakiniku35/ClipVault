import AppKit
import Combine
import Foundation

/// Polls the general pasteboard and emits a `ClipItem` for every new text copy
/// that is not excluded by the user's rules.
@MainActor
final class ClipboardMonitor: ObservableObject {
    /// Pasteboard type we attach when ClipVault itself writes to the pasteboard,
    /// so that re-copying from history is recognised.
    static let internalMarkerType = NSPasteboard.PasteboardType("com.peterchiu.clipvault.internal")

    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    @Published var isPaused = false
    @Published private(set) var lastSkipReason: String?

    var onCapture: ((ClipItem) -> Void)?

    private let settings: AppSettings
    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var lastChangeCount: Int
    private var cancellables = Set<AnyCancellable>()

    init(settings: AppSettings, pasteboard: NSPasteboard = .general) {
        self.settings = settings
        self.pasteboard = pasteboard
        self.lastChangeCount = pasteboard.changeCount

        settings.$pollInterval
            .removeDuplicates()
            .dropFirst()
            .sink { [weak self] _ in self?.restart() }
            .store(in: &cancellables)
    }

    func start() {
        guard timer == nil else { return }
        let t = Timer(timeInterval: settings.pollInterval, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in self?.check() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func restart() {
        stop()
        start()
    }

    // MARK: - Capture

    private func check() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        if isPaused {
            lastSkipReason = "已暫停"
            return
        }

        let types = Set(pasteboard.types ?? [])
        if types.contains(Self.internalMarkerType) {
            // Written by ClipVault itself; HistoryStore already updated ordering.
            return
        }
        if settings.ignoreConcealed,
           types.contains(Self.concealedType) || types.contains(Self.transientType) || types.contains(Self.autoGeneratedType) {
            lastSkipReason = "密碼管理器 / 暫時性內容"
            return
        }

        guard let raw = pasteboard.string(forType: .string) else { return }
        let text = raw
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        let app = NSWorkspace.shared.frontmostApplication
        let bundleID = app?.bundleIdentifier
        let appName = app?.localizedName ?? "未知 App"
        let rules = settings.exclusionRules

        if rules.isAppExcluded(bundleID: bundleID) {
            lastSkipReason = "已排除的 App：\(appName)"
            return
        }

        var sourceURL: String?
        if settings.captureURLs, SourceURLResolver.isBrowser(bundleID: bundleID) {
            sourceURL = SourceURLResolver.resolve(pasteboard: pasteboard, bundleID: bundleID)
        }
        // Also respect URL rules when the copied text itself is a URL.
        let candidateURL = sourceURL ?? (ClipItem(text: text, sourceAppName: appName).looksLikeURL ? text : nil)
        if rules.isURLExcluded(candidateURL) {
            lastSkipReason = "已排除的網址：\(candidateURL ?? "")"
            return
        }

        lastSkipReason = nil
        let item = ClipItem(
            text: text,
            copiedAt: Date(),
            sourceAppName: appName,
            sourceBundleID: bundleID,
            sourceURL: sourceURL
        )
        onCapture?(item)
    }
}
